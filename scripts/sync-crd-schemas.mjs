#!/usr/bin/env node
/**
 * Vendor the eks-agent-platform CRD schemas that `platform.yaml` is validated
 * against, and verify the vendored copies against upstream at the pinned ref.
 *
 *   node scripts/sync-crd-schemas.mjs                 # re-vendor at the pinned ref
 *   node scripts/sync-crd-schemas.mjs --ref=<sha>     # re-vendor and move the pin
 *   node scripts/sync-crd-schemas.mjs --ref=latest    # the same, at upstream's newest commit
 *   node scripts/sync-crd-schemas.mjs --check         # the blocking CI gate
 *   node scripts/sync-crd-schemas.mjs --freshness     # is the pin behind upstream? (exit 2 = behind)
 *   node scripts/sync-crd-schemas.mjs --self-test     # prove the freshness report still holds its line
 *
 * The CRDs are generated by controller-gen in nanohype/eks-agent-platform under
 * `operators/config/crd/bases/`. `platform.yaml` is applied against those exact
 * schemas, so the validator needs them — but resolving them over the network at
 * gate time would make every verdict depend on whatever upstream happens to be
 * that minute, and the tempting failure handler (skip when unreachable) is the
 * exact shape of bug the gate exists to catch. So the copies live here under
 * `schemas/crd/`, and validation is a pure function of the commit under test.
 *
 * That leaves two ways for the copies to become a lie, and `--check` closes
 * both:
 *
 *   1. Tampering. Someone edits a vendored schema — widens an enum, drops a
 *      `required` entry — and the gate happily validates against the weakened
 *      copy, because the gate's only notion of the schema IS that copy.
 *      `schemas/crd/source.json` records a SHA-256 per file;
 *      `scripts/validate-platform-manifests.mjs` verifies every digest before
 *      it reads a single schema, and `--check` here re-verifies them.
 *
 *   2. A stale or hand-moved pin. Someone bumps `upstream.ref` without
 *      re-vendoring, or re-vendors without moving the pin. The digests still
 *      agree with each other while describing a commit whose schemas are
 *      different. `--check` reads each file from upstream AT THE PINNED REF and
 *      requires the bytes to be identical, so the pin and its contents cannot
 *      diverge.
 *
 * Pin fidelity is the whole of the blocking gate, deliberately. Whether the pin
 * is also the newest thing upstream has is a different question with a
 * different answer every day, and answering it here would make a required check
 * flip red because someone pushed to another repository — a verdict about a
 * commit under test must not depend on a commit that is not. `--freshness` asks
 * that question separately and runs on a schedule, never in pull-request CI.
 *
 * A different answer every day is also what the freshness report must not
 * print. It is copied verbatim into an issue body that is re-edited weekly and
 * read on whatever day someone opens it, so a commit resolved during a run is
 * correct until the next run and is presented as current for as long as the
 * issue stays open — which is how a remediation comes to name a commit that is
 * no longer the newest, and following it re-vendors to the wrong ref while
 * closing an issue that should stay open. The report therefore names the path
 * that moved and the command that resolves upstream's newest commit:
 * `--ref=latest` resolves at the moment the re-vendor runs, which is the only
 * moment the answer is wanted. `--self-test` asserts that on the emitted bytes.
 *
 * Both halves of `--check` fail loudly. An unreadable manifest, a missing
 * vendored file, an unreachable upstream, a checkout sitting on the wrong
 * commit, or a fetched file that is not a CRD all exit non-zero. No path
 * through this script reports success without having compared something.
 *
 * Upstream resolves two ways, both deterministic:
 *   - `$EKS_AGENT_PLATFORM_DIR` — a checkout. Under `--check` its HEAD must
 *     equal the pinned ref; CI checks that SHA out, and a local working tree
 *     sitting on some other commit is an error rather than a silent
 *     substitution. Every other mode reads committed history at the ref it was
 *     given, so `--ref` names both the commit the copies come from and the
 *     commit the pin lands on.
 *   - otherwise — raw.githubusercontent.com at the pinned ref.
 *
 * `latest` resolves through those same two seams — `git log -1 -- <path>` in a
 * checkout, the commits API otherwise — which is what lets `--self-test` drive
 * the verdict and the remediation it names against a real repository.
 *
 * Re-vendor when the operator's API types change: run with the new `--ref`,
 * review the schema diff, and ship it with whatever `platform.yaml` change it
 * implies.
 */
import { execFile } from "node:child_process";
import { createHash } from "node:crypto";
import { createServer } from "node:http";
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = join(SCRIPT_DIR, "..");
const SCHEMA_DIR = join(ROOT, "schemas", "crd");
const SOURCE_PATH = join(SCHEMA_DIR, "source.json");
const CHECKOUT = process.env.EKS_AGENT_PLATFORM_DIR;
const CHECK = process.argv.includes("--check");
const FRESHNESS = process.argv.includes("--freshness");
const SELF_TEST = process.argv.includes("--self-test");
const REF_ARG = process.argv.find((a) => a.startsWith("--ref="))?.slice("--ref=".length);
// The two GitHub hosts, as one seam. `--self-test` points them at a server it
// runs itself, which is the only way the network arm's own bytes get asserted;
// left alone they are the real hosts. A path that cannot be driven is a path
// whose behaviour is assumed.
const RAW_BASE = process.env.CRD_RAW_BASE ?? "https://raw.githubusercontent.com";
const API_BASE = process.env.CRD_API_BASE ?? "https://api.github.com";

const exec = promisify(execFile);
const out = (line) => process.stdout.write(`${line}\n`);
const digest = (buf) => createHash("sha256").update(buf).digest("hex");
const isSha = (value) => typeof value === "string" && /^[0-9a-f]{40}$/.test(value);

function die(message, remedy) {
  process.stderr.write(`\n  ✗ ${message}\n${remedy ? `    ${remedy}\n` : ""}\n`);
  process.exit(1);
}

/**
 * Read the pin manifest. Every rule here exists because breaking it makes the
 * gate's verdict mean less than it appears to.
 */
async function readSourceManifest() {
  let manifest;
  try {
    manifest = JSON.parse(await readFile(SOURCE_PATH, "utf8"));
  } catch (err) {
    die(
      `cannot read schemas/crd/source.json (${err.message})`,
      "The vendored schemas and their source manifest travel together — restore both.",
    );
  }
  const { upstream, files } = manifest;
  if (!upstream?.repository || !upstream?.path) {
    die("schemas/crd/source.json is missing `upstream.repository` or `upstream.path`");
  }
  if (!isSha(upstream.ref)) {
    die(
      "schemas/crd/source.json `upstream.ref` must be a full 40-character commit SHA, got " +
        JSON.stringify(upstream.ref),
      "A branch name would make the gate's verdict depend on when it ran.",
    );
  }
  if (!Array.isArray(files) || files.length === 0) {
    die("schemas/crd/source.json declares no schema files");
  }
  for (const entry of files) {
    if (!entry?.file) die("schemas/crd/source.json has a `files` entry with no `file`");
    if (!/^[0-9a-f]{64}$/.test(entry.sha256 ?? "")) {
      die(`schemas/crd/source.json entry ${entry.file} carries no valid sha256 digest`);
    }
  }
  return manifest;
}

/**
 * Every `.yaml` under schemas/crd/ must be declared. An undeclared schema file
 * is un-digested and un-compared — exactly the blind spot the manifest exists
 * to remove.
 */
async function assertNoUndeclaredSchemas(manifest) {
  const declared = new Set(manifest.files.map((f) => f.file));
  const present = (await readdir(SCHEMA_DIR)).filter((f) => f.endsWith(".yaml"));
  const undeclared = present.filter((f) => !declared.has(f));
  if (undeclared.length > 0) {
    die(
      `schemas/crd/ holds files not declared in source.json: ${undeclared.join(", ")}`,
      "Add them to `files` with digests, or delete them — an undeclared schema is never verified.",
    );
  }
}

/**
 * The newest upstream commit touching the vendored path — what `--ref=latest`
 * resolves to.
 *
 * Resolved through the two seams `upstreamReader` already declares, so the
 * remediation the freshness report names can be driven against a real
 * repository rather than only against whatever github.com says this minute.
 *
 * Deliberately the newest commit touching `upstream.path`, not the newest
 * commit upstream has. The pin describes where the schemas came from; landing
 * it on a commit that changed something else would name a commit the schema
 * diff does not end at.
 */
async function resolveUpstreamHead(manifest) {
  const { repository, path } = manifest.upstream;

  if (CHECKOUT) {
    // A shallow clone answers this question with whatever it happens to hold,
    // and the answer looks identical to the true one. Refuse rather than pin to
    // it.
    let shallow;
    try {
      const { stdout } = await exec("git", [
        "-C",
        CHECKOUT,
        "rev-parse",
        "--is-shallow-repository",
      ]);
      shallow = stdout.trim();
    } catch (err) {
      die(
        `$EKS_AGENT_PLATFORM_DIR=${CHECKOUT} is not a readable git checkout (${err.message})`,
        `Point it at a checkout of ${repository}, or unset it to ask GitHub instead.`,
      );
    }
    if (shallow === "true") {
      die(
        `$EKS_AGENT_PLATFORM_DIR=${CHECKOUT} is a shallow clone`,
        "Resolving the newest commit for a path needs history — check out with `fetch-depth: 0`.",
      );
    }
    let head;
    try {
      const { stdout } = await exec("git", [
        "-C",
        CHECKOUT,
        "log",
        "-1",
        "--format=%H",
        "--",
        path,
      ]);
      head = stdout.trim();
    } catch (err) {
      die(
        `cannot resolve the newest commit for ${path} in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT} (${err.message})`,
        `Point it at a checkout of ${repository}, or unset it to ask GitHub instead.`,
      );
    }
    if (!isSha(head)) {
      die(
        `no commit in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT} touches ${path}`,
        `Is ${CHECKOUT} a checkout of ${repository}?`,
      );
    }
    return head;
  }

  const url = `${API_BASE}/repos/${repository}/commits?path=${encodeURIComponent(path)}&per_page=1`;
  const token = process.env.GITHUB_TOKEN ?? process.env.GH_TOKEN;
  let response;
  try {
    response = await fetch(url, {
      headers: {
        Accept: "application/vnd.github+json",
        // Unauthenticated this endpoint allows 60 requests an hour per address,
        // and a rate-limited lookup must not read as an unresolvable path.
        ...(token ? { Authorization: `Bearer ${token}` } : {}),
      },
    });
  } catch (err) {
    die(
      `cannot ask GitHub for the newest commit touching ${path} (${err.message})`,
      "Resolving upstream's newest commit is the point of `--ref=latest` — it does not fall back to the pin.",
    );
  }
  if (!response.ok) {
    die(
      `cannot ask GitHub for the newest commit touching ${path}: HTTP ${response.status} ${response.statusText}`,
      "A rate-limited or unreachable lookup is not an answer — retry, or pass the 40-character SHA directly.",
    );
  }
  const commits = await response.json();
  const head = Array.isArray(commits) ? commits[0]?.sha : undefined;
  if (!isSha(head)) {
    die(
      `GitHub returned no commit touching ${path} in ${repository}`,
      "Has the path been renamed upstream? Re-vendor against its new location.",
    );
  }
  return head;
}

/** Resolve an upstream reader for `ref`, failing loudly if it cannot be reached. */
async function upstreamReader(manifest, ref) {
  const { repository, path } = manifest.upstream;

  if (CHECKOUT) {
    let head;
    try {
      const { stdout } = await exec("git", ["-C", CHECKOUT, "rev-parse", "HEAD"]);
      head = stdout.trim();
    } catch (err) {
      die(
        `$EKS_AGENT_PLATFORM_DIR=${CHECKOUT} is not a readable git checkout (${err.message})`,
        `Point it at a checkout of ${repository}, or unset it to read from GitHub instead.`,
      );
    }
    if (CHECK && head !== ref) {
      die(
        `$EKS_AGENT_PLATFORM_DIR is at ${head}, but schemas/crd/source.json pins ${ref}`,
        "--check compares against the pinned commit. Check that SHA out, or unset the variable.",
      );
    }
    // `--check` compares against the working tree, which is why it insists the
    // checkout sits on the pin: the bytes it reads and the commit it names are
    // then the same thing. Every other mode reads git objects at `ref` instead,
    // so `--ref` — and therefore `--ref=latest` — moves the copies and the pin
    // to the commit it names rather than to wherever the checkout happens to
    // stand.
    if (CHECK) {
      return {
        origin: `${CHECKOUT} @ ${head}`,
        head,
        async read(file) {
          const from = join(CHECKOUT, path, file);
          try {
            return await readFile(from);
          } catch (err) {
            die(
              `cannot read ${from} (${err.message})`,
              `Is ${CHECKOUT} a checkout of ${repository}?`,
            );
          }
        },
      };
    }

    return {
      origin: `${CHECKOUT} @ ${ref}`,
      head: ref,
      async read(file) {
        const at = `${ref}:${path}/${file}`;
        const bytes = await gitShow(CHECKOUT, ref, `${path}/${file}`);
        if (bytes === null) {
          die(
            `cannot read ${at} from ${CHECKOUT}`,
            `Is ${CHECKOUT} a checkout of ${repository} with ${ref.slice(0, 12)} reachable?`,
          );
        }
        return bytes;
      },
    };
  }

  return {
    origin: `${repository}@${ref} (raw.githubusercontent.com)`,
    head: ref,
    async read(file) {
      return await fetchAtRef(repository, path, ref, file);
    },
  };
}

/**
 * Read one schema from raw.githubusercontent.com at `ref`. Never degrades into a
 * skip: a transport failure or any status but 200 and 404 stops the run.
 *
 * With `allowMissing`, a 404 returns null rather than dying — "the file is not
 * there at that ref" is an answer the freshness comparison needs, and only for
 * the tip side. A 404 at the pin remains fatal, because a pin whose files have
 * gone is a broken pin rather than a report.
 */
async function fetchAtRef(repository, path, ref, file, allowMissing = false) {
  const url = `${RAW_BASE}/${repository}/${ref}/${path}/${file}`;
  let response;
  try {
    response = await fetch(url);
  } catch (err) {
    die(
      `cannot fetch ${url} (${err.message})`,
      "The upstream comparison is the point of this check — it does not degrade into a skip.",
    );
  }
  if (response.status === 404 && allowMissing) return null;
  if (!response.ok) {
    die(
      `cannot fetch ${url}: HTTP ${response.status} ${response.statusText}`,
      "A ref that no longer resolves is a broken pin, not a passing check.",
    );
  }
  return Buffer.from(await response.arrayBuffer());
}

/**
 * One reader over both seams for the freshness comparison, so the report has one
 * body rather than one per seam.
 *
 * The sentences the report prints are the part that can go stale, and a report
 * assembled twice is a report whose two halves can drift — one arm gaining a
 * commit id the gate never drives. `readAt` is the only thing that differs
 * between a checkout and the network; everything above it is shared, so driving
 * either seam asserts the bytes both produce.
 *
 * `readAt` returns null only for "absent at that ref". Every other failure dies.
 */
async function freshnessReader({ upstream: { repository, path, ref } }) {
  if (CHECKOUT) {
    try {
      await exec("git", ["-C", CHECKOUT, "cat-file", "-e", `${ref}^{commit}`]);
    } catch {
      die(
        `${ref.slice(0, 12)} is not present in $EKS_AGENT_PLATFORM_DIR=${CHECKOUT}`,
        "Check the repository out with full history (fetch-depth: 0) so the pinned commit is reachable.",
      );
    }
    return {
      async readAt(at, file) {
        // Absence is asked separately from content, so a git failure that is not
        // absence cannot be read as a deleted file.
        try {
          await exec("git", ["-C", CHECKOUT, "cat-file", "-e", `${at}:${path}/${file}`]);
        } catch {
          return null;
        }
        const bytes = await gitShow(CHECKOUT, at, `${path}/${file}`);
        if (bytes === null) {
          die(
            `cannot read ${at}:${path}/${file} from ${CHECKOUT}`,
            `Is ${CHECKOUT} a checkout of ${repository}?`,
          );
        }
        return bytes;
      },
    };
  }
  return {
    async readAt(at, file) {
      return await fetchAtRef(repository, path, at, file, at === "HEAD");
    },
  };
}

/**
 * Report whether the pin is behind upstream's default branch.
 *
 * Deliberately not part of `--check`: the answer changes when someone pushes to
 * eks-agent-platform, so wiring it into pull-request CI would turn an unrelated
 * upstream commit into a red required check on every open branch here. It runs
 * on a schedule instead (`.github/workflows/crd-schema-freshness.yml`), where a
 * red run is a notification that the operator API moved, not a merge blocker.
 *
 * Reads both sides at a ref rather than from a working tree, so a checkout on
 * any commit answers correctly as long as the pinned commit is reachable.
 *
 * What it prints is the load-bearing part. This report is copied verbatim into
 * an issue body that is re-edited weekly and read on whatever day someone opens
 * it, so a commit resolved by one run is presented as current for as long as
 * the issue stays open. It therefore names the path that moved, the files that
 * moved, and a command that resolves upstream's newest commit when it runs —
 * never a commit this run resolved. Both sides are compared at a ref (`HEAD` on
 * either seam) and that ref is never resolved to a commit id, so there is no
 * upstream sha in scope here to print by accident — the property is structural
 * rather than a rule the emitter has to keep remembering.
 *
 * One body over `freshnessReader`, not one per seam: a report assembled twice is
 * a report whose halves can drift, and only one of them would be driven.
 */
async function reportFreshness(manifest) {
  const { repository, path, ref } = manifest.upstream;
  const reader = await freshnessReader(manifest);
  const behind = [];

  for (const { file } of manifest.files) {
    const [atPin, atTip] = await Promise.all([
      reader.readAt(ref, file),
      reader.readAt("HEAD", file),
    ]);
    if (atPin === null) {
      die(
        `${path}/${file} does not exist at ${repository}@${ref.slice(0, 12)}`,
        "The pin predates this CRD, or the file was renamed — re-vendor and repin.",
      );
    }
    if (atTip === null) {
      behind.push(`${file} — removed or renamed upstream since the pin`);
    } else if (!atPin.equals(atTip)) {
      behind.push(`${file} — changed upstream since the pin`);
    }
  }

  if (behind.length === 0) {
    out(`✓ the pin ${ref.slice(0, 12)} is current with ${path} in ${repository}`);
    return;
  }

  // `--ref=latest` and the `...HEAD` in the compare link are the same move: each
  // resolves when it is used rather than when this ran, so both stay correct on
  // whatever day the issue carrying them is read. A sha here would be correct
  // until the next Monday and would keep being presented as current afterwards.
  process.stderr.write(
    `\n  ✗ the pin ${ref.slice(0, 12)} is behind — ${path} in ${repository} has changed since it:\n` +
      `${behind.map((b) => `      ${b}`).join("\n")}\n` +
      "\n    Nothing is broken — the vendored copies still match the commit they claim.\n" +
      "    Adopt the newer operator API when convenient:\n" +
      "\n      npm run schemas:sync -- --ref=latest\n      git diff schemas/crd/\n" +
      "      npm run platform:validate\n" +
      "\n    The second command is the schema diff, exactly — a new bound upstream usually\n" +
      `    implies a platform.yaml change here. To read it before re-vendoring:\n` +
      `    https://github.com/${repository}/compare/${ref.slice(0, 12)}...HEAD\n\n`,
  );
  // Exit 2, not 1, and the distinction is load-bearing. `die` exits 1 for every
  // way this check can BREAK — an unreachable upstream, a ref that no longer
  // resolves, a fetched file that is not a CRD. "The pin is behind" is a
  // different fact from "I could not find out", and the scheduled workflow files
  // an issue for the first while failing loudly for the second. Collapsed into
  // one code, a month of failed lookups reads as a month of confirmed drift.
  process.exit(2);
}

/** `git show <ref>:<path>` as a Buffer, or null when the path is absent at that ref. */
async function gitShow(dir, ref, path) {
  try {
    const { stdout } = await exec("git", ["-C", dir, "show", `${ref}:${path}`], {
      encoding: "buffer",
      maxBuffer: 64 * 1024 * 1024,
    });
    return stdout;
  } catch {
    return null;
  }
}

/* ────────────────────────────── self-test ───────────────────────────── */

/**
 * Assert what the freshness report says, by running it.
 *
 * The report is copied verbatim into an issue body that is re-edited weekly and
 * read on whatever day someone opens it. A commit resolved during a run and
 * printed there is correct until the next run and is presented as current for
 * as long as the issue stays open — which is how a remediation comes to name a
 * commit that is no longer the newest. Following it re-vendors to the wrong ref
 * and closes an issue that should stay open: a wrong instruction that also
 * dismisses its own warning.
 *
 * So the property is about the emitted bytes, not about the code that builds
 * them. A construction that reads correctly today can be rewritten to print the
 * sha somewhere else and still read correctly; only an assertion on the output
 * refuses that. Each case here builds a real upstream repository whose commits
 * it knows, runs the shipped script against it through the checkout seam the
 * script already declares, and looks for those commits in what comes back.
 *
 * The fixture is built so that no two of the three commits a wrong answer could
 * name are ever the same commit. Its newest commit does not touch the vendored
 * path, so a resolver reaching for the checkout's HEAD rather than the path's
 * newest commit is not indistinguishable from a correct one. And the path's
 * newest commit RESTORES bytes an earlier commit already had, so a pin can be
 * current while still not being the newest commit touching the path — without
 * that, "the pin" and "what upstream resolves to" coincide in the current case,
 * a sha printed there is stripped as the pin, and the exit-0 message becomes a
 * place to hide one.
 *
 * What this covers and what it does not: it drives the checkout seam, which is
 * the one a fixture can control. The GitHub seam differs only in how the two
 * sides are read — neither arm resolves upstream's tip to a commit id at all,
 * and both hand the same sentences to one emitter — so the bytes asserted here
 * are the bytes that arm emits. It is not a substitute for the network path
 * being reachable, which `--freshness` fails loudly on rather than skipping.
 */

const SELF_TEST_SCHEMAS = [
  "platform.example.dev_widgets.yaml",
  "platform.example.dev_gadgets.yaml",
];
const SELF_TEST_REPO = "example/upstream";
const SELF_TEST_PATH = "operators/config/crd/bases";

/** Run the shipped script inside `tree`. Never throws — the exit code is the verdict. */
async function runScript(tree, args, env) {
  const environment = { ...process.env, ...env };
  for (const [key, value] of Object.entries(env)) {
    if (value === undefined) delete environment[key];
  }
  // Under Actions these two files are prose the reader sees, exactly like
  // stdout — a step summary renders on the run page and a job output flows into
  // the issue body. Scanning only the streams would leave a place to put a
  // resolved commit that no assertion looks at, so they are pointed at the
  // fixture and folded into what the assertions read.
  const summary = join(tree, "step-summary.txt");
  const output = join(tree, "job-output.txt");
  environment.GITHUB_STEP_SUMMARY = summary;
  environment.GITHUB_OUTPUT = output;
  await writeFile(summary, "");
  await writeFile(output, "");

  let code = 0;
  let streams = "";
  try {
    const { stdout, stderr } = await exec(
      "node",
      [join(tree, "scripts", "sync-crd-schemas.mjs"), ...args],
      { cwd: tree, env: environment, maxBuffer: 16 * 1024 * 1024 },
    );
    streams = `${stdout}${stderr}`;
  } catch (err) {
    code = err.code ?? 1;
    streams = `${err.stdout ?? ""}${err.stderr ?? ""}`;
  }
  const sidecars = `${await readFile(summary, "utf8")}${await readFile(output, "utf8")}`;
  return { code, output: `${streams}${sidecars}` };
}

/**
 * An upstream repository with a history the caller knows: a base, a commit that
 * changes a schema, a commit that changes it again, a commit that changes it
 * back, and a newest commit that touches nothing vendored.
 *
 * `restored` and `moved` hold identical bytes at different commits. That is what
 * lets a pin at `moved` read current while the path's newest commit is
 * `restored`, which is the only arrangement in which the exit-0 report has an
 * upstream commit id available to print that is not also the pin.
 */
async function buildUpstream(dir) {
  const git = (...args) => exec("git", ["-C", dir, ...args]);
  const revision = () => git("rev-parse", "HEAD").then(({ stdout }) => stdout.trim());
  const body = (name, rev) =>
    "apiVersion: apiextensions.k8s.io/v1\n" +
    "kind: CustomResourceDefinition\n" +
    `metadata:\n  name: ${name}\nspec:\n  revision: ${rev}\n`;

  await mkdir(join(dir, SELF_TEST_PATH), { recursive: true });
  await exec("git", ["init", "-q", "-b", "main", dir]);
  await git("config", "user.email", "self-test@digest-pipeline.invalid");
  await git("config", "user.name", "freshness self-test");
  await git("config", "commit.gpgsign", "false");

  for (const file of SELF_TEST_SCHEMAS) {
    await writeFile(join(dir, SELF_TEST_PATH, file), body(file, 1));
  }
  await git("add", "-A");
  await git("commit", "-qm", "the schemas as the pin found them");
  const base = await revision();

  await writeFile(join(dir, SELF_TEST_PATH, SELF_TEST_SCHEMAS[0]), body(SELF_TEST_SCHEMAS[0], 2));
  await git("add", "-A");
  await git("commit", "-qm", "a schema gains a bound");
  const moved = await revision();

  await writeFile(join(dir, SELF_TEST_PATH, SELF_TEST_SCHEMAS[0]), body(SELF_TEST_SCHEMAS[0], 3));
  await git("add", "-A");
  await git("commit", "-qm", "the bound is reworked");
  await writeFile(join(dir, SELF_TEST_PATH, SELF_TEST_SCHEMAS[0]), body(SELF_TEST_SCHEMAS[0], 2));
  await git("add", "-A");
  await git("commit", "-qm", "the rework is reverted");
  const restored = await revision();

  await writeFile(join(dir, "README.md"), "a commit that touches nothing vendored\n");
  await git("add", "-A");
  await git("commit", "-qm", "something else entirely");
  const head = await revision();

  return { base, moved, restored, head };
}

/** A repository the script can run in: vendored copies at `ref`, pinned to `ref`. */
async function buildTree(scratch, name, upstreamDir, ref) {
  const tree = join(scratch, name);
  await mkdir(join(tree, "schemas", "crd"), { recursive: true });
  await mkdir(join(tree, "scripts"), { recursive: true });
  await writeFile(
    join(tree, "scripts", "sync-crd-schemas.mjs"),
    await readFile(join(SCRIPT_DIR, "sync-crd-schemas.mjs")),
  );

  const files = [];
  for (const file of SELF_TEST_SCHEMAS) {
    const bytes = await gitShow(upstreamDir, ref, `${SELF_TEST_PATH}/${file}`);
    await writeFile(join(tree, "schemas", "crd", file), bytes);
    files.push({ file, sha256: digest(bytes) });
  }
  const manifest = {
    upstream: { repository: SELF_TEST_REPO, path: SELF_TEST_PATH, ref },
    files,
  };
  await writeFile(
    join(tree, "schemas", "crd", "source.json"),
    `${JSON.stringify(manifest, null, 2)}\n`,
  );
  return tree;
}

/**
 * The commit id `text` names, or null. The pin is stripped first: it is a fact
 * about the commit under test, not a value resolved during the run, and it does
 * not go stale. Abbreviations are checked down to seven characters, because
 * `slice(0, 12)` is the form this repository prints and a grep for the full
 * forty would walk straight past it.
 */
function namesACommit(text, pin, commits) {
  let stripped = text.toLowerCase();
  for (const form of [pin, pin.slice(0, 12), pin.slice(0, 7), pin.slice(0, 4)]) {
    stripped = stripped.split(form.toLowerCase()).join("");
  }
  // Bounded on both sides: a sha256 digest contains a 40-character hex run, and
  // reading that as a commit id would make the detector fire on output that
  // names no commit at all.
  if (/(?<![0-9a-f])[0-9a-f]{40}(?![0-9a-f])/.test(stripped)) return "a 40-character commit id";
  for (const sha of commits) {
    // Down to four, git's own `--abbrev` floor. Below it nothing resolves, so
    // there is no shorter form that is still an instruction someone can follow;
    // above it, every abbreviation git will print is refused.
    for (let length = sha.length; length >= 4; length--) {
      if (stripped.includes(sha.slice(0, length).toLowerCase())) {
        return `${sha.slice(0, 12)}, abbreviated to ${length} characters`;
      }
    }
  }
  return null;
}

/**
 * The two GitHub endpoints this script reads, served from a fixture repository.
 *
 * The scheduled workflow sets no `EKS_AGENT_PLATFORM_DIR`, so the arm that runs
 * in production is the network one. A gate that drives only the checkout arm
 * asserts a path production never executes; both seams have to answer for their
 * own bytes.
 *
 * Only the two shapes the script depends on: raw contents at a ref, and the
 * newest commit touching a path. A 404 is served for a file absent at that ref,
 * which is the case the report has to tell apart from a failure.
 */
async function serveUpstream(dir) {
  const server = createServer((req, res) => {
    const url = new URL(req.url, "http://fixture.invalid");
    const commits = url.pathname.match(/^\/repos\/(.+)\/commits$/);
    if (commits) {
      const path = url.searchParams.get("path");
      exec("git", ["-C", dir, "log", "-1", "--format=%H", "--", path])
        .then(({ stdout }) => {
          res.writeHead(200, { "content-type": "application/json" });
          res.end(JSON.stringify([{ sha: stdout.trim() }]));
        })
        .catch(() => {
          res.writeHead(500);
          res.end("[]");
        });
      return;
    }
    // /<owner>/<repo>/<ref>/<path...>
    const raw = url.pathname.slice(1).split("/");
    const [, , ref, ...rest] = raw;
    gitShow(dir, ref, rest.join("/"))
      .then((bytes) => {
        if (bytes === null) {
          res.writeHead(404);
          res.end("404: Not Found");
          return;
        }
        res.writeHead(200);
        res.end(bytes);
      })
      .catch(() => {
        res.writeHead(500);
        res.end("");
      });
  });
  await new Promise((resolve) => server.listen(0, "127.0.0.1", resolve));
  const { port } = server.address();
  return { base: `http://127.0.0.1:${port}`, close: () => new Promise((r) => server.close(r)) };
}

/**
 * A second upstream, where the newest commit deletes a vendored schema.
 *
 * controller-gen filenames change exactly when an API group or kind is renamed,
 * which is the drift most likely to stop `platform.yaml` validating — and the
 * only case where the two seams answer through different mechanics, a missing
 * git object on one and a 404 on the other. Both have to call it removal rather
 * than report the pin as current.
 */
async function buildRemovalUpstream(dir) {
  const git = (...args) => exec("git", ["-C", dir, ...args]);
  await mkdir(join(dir, SELF_TEST_PATH), { recursive: true });
  await exec("git", ["init", "-q", "-b", "main", dir]);
  await git("config", "user.email", "self-test@digest-pipeline.invalid");
  await git("config", "user.name", "freshness self-test");
  await git("config", "commit.gpgsign", "false");

  for (const file of SELF_TEST_SCHEMAS) {
    await writeFile(
      join(dir, SELF_TEST_PATH, file),
      `apiVersion: apiextensions.k8s.io/v1\nkind: CustomResourceDefinition\nmetadata:\n  name: ${file}\n`,
    );
  }
  await git("add", "-A");
  await git("commit", "-qm", "both schemas exist");
  const { stdout } = await git("rev-parse", "HEAD");

  await git("rm", "-q", `${SELF_TEST_PATH}/${SELF_TEST_SCHEMAS[1]}`);
  await git("commit", "-qm", "a kind is renamed, so its file goes");
  return stdout.trim();
}

async function runSelfTest() {
  const scratch = await mkdtemp(join(tmpdir(), "crd-freshness-selftest-"));
  const cases = [];
  const record = (name, passed, detail) => cases.push({ name, passed, detail });
  let server;

  try {
    const upstreamDir = join(scratch, "upstream");
    const { base, moved, restored, head } = await buildUpstream(upstreamDir);
    server = await serveUpstream(upstreamDir);
    const commits = [base, moved, restored, head];
    const env = { EKS_AGENT_PLATFORM_DIR: upstreamDir };

    // The fixture's own premise, asserted rather than assumed. If a later edit
    // collapses these into one commit, every case below still passes while the
    // exit-0 report quietly regains somewhere to hide a resolved commit id.
    const atMoved = await gitShow(upstreamDir, moved, `${SELF_TEST_PATH}/${SELF_TEST_SCHEMAS[0]}`);
    const atRestored = await gitShow(
      upstreamDir,
      restored,
      `${SELF_TEST_PATH}/${SELF_TEST_SCHEMAS[0]}`,
    );
    record(
      "the fixture holds the same schema bytes at two different commits",
      moved !== restored && atMoved.equals(atRestored),
      "the fixture degenerated — a current pin can no longer differ from the path's newest commit",
    );
    record(
      "the fixture's newest commit is not the newest to touch the vendored path",
      head !== restored,
      "the fixture degenerated — resolving HEAD is no longer distinguishable from resolving the path",
    );

    /* ── the detector, before anything is asked of it ────────────────── */
    // A detector that has never returned non-null is indistinguishable from one
    // that cannot. Every staleness case below asserts `=== null`, so without
    // these two the whole class passes by doing nothing.
    record(
      "the detector finds a commit id an abbreviation short of git's own floor",
      namesACommit(`re-vendor with ${restored.slice(0, 4)}`, base, commits) !== null,
      "it walked past a four-character abbreviation",
    );
    record(
      "the detector finds one printed in upper case",
      namesACommit(`upstream is at ${restored.slice(0, 12).toUpperCase()}`, base, commits) !== null,
      "it walked past an upper-case abbreviation",
    );
    record(
      "the detector does not mistake a sha256 digest for a commit id",
      namesACommit(`sha256 ${digest(Buffer.from("not a commit"))}`, base, commits) === null,
      "a 64-character digest was read as a 40-character commit id",
    );
    record(
      "the detector lets the pin through, since the pin does not go stale",
      namesACommit(`the pin ${base.slice(0, 12)} is behind`, base, commits) === null,
      "it flagged the pin, which is a property of the tree rather than of the run",
    );

    /* ── a behind pin: the verdict, and what the verdict says ────────── */
    const behindTree = await buildTree(scratch, "behind", upstreamDir, base);
    const behind = await runScript(behindTree, ["--freshness"], env);

    record(
      "a behind pin exits 2, the code the scheduled workflow files an issue on",
      behind.code === 2,
      `exited ${behind.code}`,
    );
    const namedWhenBehind = namesACommit(behind.output, base, commits);
    record(
      "the behind report names no upstream commit id",
      namedWhenBehind === null,
      namedWhenBehind ? `it names ${namedWhenBehind}` : undefined,
    );
    record(
      "the behind report names a command that resolves upstream HEAD when it runs",
      behind.output.includes("--ref=latest"),
      "no `--ref=latest` in the output",
    );
    record(
      "the behind report leaves the reader no placeholder to resolve",
      !behind.output.includes("--ref=<sha>"),
      "it still names `--ref=<sha>`",
    );
    record(
      "the behind report names the path that moved",
      behind.output.includes(SELF_TEST_PATH),
      `no ${SELF_TEST_PATH} in the output`,
    );

    /* ── and the command it names does what it says ──────────────────── */
    const adoptTree = await buildTree(scratch, "adopt", upstreamDir, base);
    const adopt = await runScript(adoptTree, ["--ref=latest"], env);
    record("`--ref=latest` re-vendors without error", adopt.code === 0, adopt.output.trim());

    const pinned = JSON.parse(
      await readFile(join(adoptTree, "schemas", "crd", "source.json"), "utf8"),
    );
    record(
      "`--ref=latest` lands the pin on the newest commit touching the vendored path",
      pinned.upstream.ref === restored,
      pinned.upstream.ref === head
        ? "it landed on the checkout's HEAD, which changed nothing vendored"
        : pinned.upstream.ref === base
          ? "it fell back to the pin it was told to move off"
          : `it landed on ${pinned.upstream.ref}`,
    );

    const wanted = await gitShow(
      upstreamDir,
      restored,
      `${SELF_TEST_PATH}/${SELF_TEST_SCHEMAS[0]}`,
    );
    const landed = await readFile(join(adoptTree, "schemas", "crd", SELF_TEST_SCHEMAS[0]));
    record(
      "`--ref=latest` brings the bytes at that commit, not the ones the pin held",
      landed.equals(wanted),
      "the vendored copy is not what upstream holds at the commit now pinned",
    );

    let digestsAgree = true;
    for (const entry of pinned.files) {
      const onDisk = await readFile(join(adoptTree, "schemas", "crd", entry.file));
      if (digest(onDisk) !== entry.sha256) digestsAgree = false;
    }
    record(
      "`--ref=latest` rewrites the digests to describe what it wrote",
      digestsAgree,
      "source.json records a digest no vendored file has",
    );

    // The instruction has to leave the tree in a state the blocking gate
    // accepts, or following it trades a stale issue for a red required check.
    await exec("git", ["-C", upstreamDir, "checkout", "-q", restored]);
    const gate = await runScript(adoptTree, ["--check"], env);
    record(
      "the commit `--ref=latest` chose is one the blocking gate accepts",
      gate.code === 0,
      gate.output.trim(),
    );
    await exec("git", ["-C", upstreamDir, "checkout", "-q", head]);

    /* ── and a sync that was asked for nothing moves nothing ─────────── */
    // The checkout stands on a commit that is not the pin, which is the normal
    // state of a local clone. Reading the working tree here would vendor bytes
    // from a commit nobody named and rewrite the pin to the checkout's HEAD — a
    // pin move nobody asked for, arriving as an unexplained diff.
    const quietTree = await buildTree(scratch, "quiet", upstreamDir, base);
    const quiet = await runScript(quietTree, [], env);
    record(
      "a plain sync against a checkout re-vendors without error",
      quiet.code === 0,
      quiet.output.trim(),
    );

    const quietPin = JSON.parse(
      await readFile(join(quietTree, "schemas", "crd", "source.json"), "utf8"),
    );
    record(
      "a sync given no ref leaves the pin where it was",
      quietPin.upstream.ref === base,
      `the pin moved to ${quietPin.upstream.ref}`,
    );
    const atBase = await gitShow(upstreamDir, base, `${SELF_TEST_PATH}/${SELF_TEST_SCHEMAS[0]}`);
    const quietBytes = await readFile(join(quietTree, "schemas", "crd", SELF_TEST_SCHEMAS[0]));
    record(
      "a sync given no ref vendors the pin's bytes, not the checkout's working tree",
      quietBytes.equals(atBase),
      "it vendored bytes from a commit nobody named",
    );

    /* ── the same questions, over the seam production actually uses ─── */
    // No EKS_AGENT_PLATFORM_DIR: the arm the scheduled workflow runs. The
    // report body is shared, but "shared" is a claim until both seams are made
    // to produce it.
    const netEnv = {
      EKS_AGENT_PLATFORM_DIR: undefined,
      CRD_RAW_BASE: server.base,
      CRD_API_BASE: server.base,
    };

    const netBehindTree = await buildTree(scratch, "net-behind", upstreamDir, base);
    const netBehind = await runScript(netBehindTree, ["--freshness"], netEnv);
    record(
      "the network seam reaches the same verdict for a behind pin",
      netBehind.code === 2,
      `exited ${netBehind.code}: ${netBehind.output.trim()}`,
    );
    const namedOverNetwork = namesACommit(netBehind.output, base, commits);
    record(
      "the network seam's behind report names no upstream commit id",
      namedOverNetwork === null,
      namedOverNetwork ? `it names ${namedOverNetwork}` : undefined,
    );
    record(
      "the network seam's behind report names the same command",
      netBehind.output.includes("--ref=latest") && !netBehind.output.includes("--ref=<sha>"),
      "the two seams disagree about the remediation",
    );

    const netAdoptTree = await buildTree(scratch, "net-adopt", upstreamDir, base);
    const netAdopt = await runScript(netAdoptTree, ["--ref=latest"], netEnv);
    const netPin = JSON.parse(
      await readFile(join(netAdoptTree, "schemas", "crd", "source.json"), "utf8"),
    );
    record(
      "`--ref=latest` resolves over the network seam too, not only from a checkout",
      netAdopt.code === 0 && netPin.upstream.ref === restored,
      `exited ${netAdopt.code}, pin ${netPin.upstream.ref}`,
    );

    /* ── the failures that must not read as drift ─────────────────────── */
    // Exit 1 and exit 2 are different facts, and the workflow branches on the
    // difference: 2 files a drift issue, anything else fails the job as "could
    // not reach a verdict". Collapsed into one code, a month of failed lookups
    // reads as a month of confirmed drift.
    const absent = "0123456789abcdef0123456789abcdef01234567";
    const missingPinTree = await buildTree(scratch, "missing-pin", upstreamDir, base);
    const manifestPath = join(missingPinTree, "schemas", "crd", "source.json");
    const broken = JSON.parse(await readFile(manifestPath, "utf8"));
    broken.upstream.ref = absent;
    await writeFile(manifestPath, `${JSON.stringify(broken, null, 2)}\n`);
    const unreachable = await runScript(missingPinTree, ["--freshness"], env);
    record(
      "a pin no checkout holds exits 1, not the 2 that means confirmed drift",
      unreachable.code === 1,
      `exited ${unreachable.code}`,
    );

    const netUnreachable = await runScript(missingPinTree, ["--freshness"], {
      ...netEnv,
      CRD_RAW_BASE: "http://127.0.0.1:1/unreachable",
      CRD_API_BASE: "http://127.0.0.1:1/unreachable",
    });
    record(
      "an unreachable upstream exits 1, and is never reported as current",
      netUnreachable.code === 1,
      `exited ${netUnreachable.code}`,
    );

    // The guard's own comment says a shallow clone's wrong answer is
    // indistinguishable from a right one, which is exactly why it cannot be left
    // to inspection.
    const shallowDir = join(scratch, "shallow");
    await exec("git", ["clone", "--quiet", "--depth", "1", `file://${upstreamDir}`, shallowDir]);
    const shallowTree = await buildTree(scratch, "shallow-tree", upstreamDir, base);
    const shallow = await runScript(shallowTree, ["--ref=latest"], {
      EKS_AGENT_PLATFORM_DIR: shallowDir,
    });
    record(
      "`--ref=latest` refuses a shallow clone rather than pinning to what it happens to hold",
      shallow.code === 1 && /fetch-depth/.test(shallow.output),
      `exited ${shallow.code}: ${shallow.output.trim()}`,
    );

    /* ── a schema that goes away upstream, on both seams ─────────────── */
    const goneDir = join(scratch, "removed-upstream");
    const gonePin = await buildRemovalUpstream(goneDir);
    const goneServer = await serveUpstream(goneDir);
    try {
      for (const [seam, seamEnv] of [
        ["checkout", { EKS_AGENT_PLATFORM_DIR: goneDir }],
        [
          "network",
          {
            EKS_AGENT_PLATFORM_DIR: undefined,
            CRD_RAW_BASE: goneServer.base,
            CRD_API_BASE: goneServer.base,
          },
        ],
      ]) {
        const goneTree = await buildTree(scratch, `gone-${seam}`, goneDir, gonePin);
        const gone = await runScript(goneTree, ["--freshness"], seamEnv);
        record(
          `the ${seam} seam calls a schema removed upstream drift, not "current"`,
          gone.code === 2 && /removed or renamed upstream since the pin/.test(gone.output),
          `exited ${gone.code}: ${gone.output.trim()}`,
        );
      }
    } finally {
      await goneServer.close();
    }

    /* ── a current pin: the other exit prints no commit id either ────── */
    const currentTree = await buildTree(scratch, "current", upstreamDir, moved);
    const current = await runScript(currentTree, ["--freshness"], env);
    record(
      "a pin whose bytes match upstream reads current, though upstream has commits past it",
      current.code === 0,
      `exited ${current.code}: ${current.output.trim()}`,
    );
    const namedWhenCurrent = namesACommit(current.output, moved, commits);
    record(
      "the current report names no upstream commit id either",
      namedWhenCurrent === null,
      namedWhenCurrent ? `it names ${namedWhenCurrent}` : undefined,
    );
  } finally {
    if (server) await server.close();
    await rm(scratch, { recursive: true, force: true });
  }

  const failed = cases.filter((c) => !c.passed);
  out("");
  for (const c of cases) out(`  ${c.passed ? "✓" : "✗"} ${c.name}`);
  if (failed.length > 0) {
    process.stderr.write(
      `\n  ✗ ${failed.length} of ${cases.length} freshness assertion(s) do not hold:\n` +
        `${failed.map((c) => `      ${c.name}${c.detail ? ` — ${c.detail}` : ""}`).join("\n")}\n\n`,
    );
    return 1;
  }
  out(
    `\n✓ all ${cases.length} freshness assertions hold — the report names a command, not a commit`,
  );
  return 0;
}

async function main() {
  const modes = [CHECK, FRESHNESS, SELF_TEST, REF_ARG !== undefined].filter(Boolean).length;
  if (modes > 1) die("--check, --freshness, --self-test and --ref are mutually exclusive");
  if (REF_ARG !== undefined && REF_ARG !== "latest" && !isSha(REF_ARG)) {
    die(
      `--ref must be \`latest\` or a full 40-character commit SHA, got ${JSON.stringify(REF_ARG)}`,
    );
  }

  // Ahead of the manifest read: the self-test builds its own tree and its own
  // upstream, so it must run in any checkout rather than only in one whose
  // schemas/crd/ already validates.
  if (SELF_TEST) process.exit(await runSelfTest());

  const manifest = await readSourceManifest();
  await assertNoUndeclaredSchemas(manifest);

  if (FRESHNESS) {
    await reportFreshness(manifest);
    return;
  }

  // `latest` resolves here, at the moment the re-vendor runs. That is what the
  // freshness report names, so the instruction it carries stays correct however
  // long the issue carrying it has been open.
  const ref =
    REF_ARG === "latest" ? await resolveUpstreamHead(manifest) : (REF_ARG ?? manifest.upstream.ref);
  const source = await upstreamReader(manifest, ref);

  const tampered = [];
  const drifted = [];
  const files = [];

  for (const entry of manifest.files) {
    const upstream = await source.read(entry.file);
    if (!upstream.toString("utf8").includes("kind: CustomResourceDefinition")) {
      die(`${entry.file} from ${source.origin} is not a CustomResourceDefinition — refusing it`);
    }
    const localPath = join(SCHEMA_DIR, entry.file);

    if (CHECK) {
      let local;
      try {
        local = await readFile(localPath);
      } catch (err) {
        die(
          `vendored schema schemas/crd/${entry.file} is missing (${err.message})`,
          "Restore it with `npm run schemas:sync`.",
        );
      }
      if (digest(local) !== entry.sha256) {
        tampered.push(
          `${entry.file} — source.json records ${entry.sha256}, on disk ${digest(local)}`,
        );
      }
      if (!local.equals(upstream)) {
        drifted.push(entry.file);
      }
    } else {
      await writeFile(localPath, upstream);
      out(`  ↻ schemas/crd/${entry.file}`);
    }

    files.push({ file: entry.file, sha256: digest(upstream) });
  }

  if (CHECK) {
    if (tampered.length > 0 || drifted.length > 0) {
      if (tampered.length > 0) {
        process.stderr.write(
          "\n  ✗ vendored CRD schemas do not match their recorded digests — they were edited " +
            `in place:\n${tampered.map((t) => `      ${t}`).join("\n")}\n`,
        );
      }
      if (drifted.length > 0) {
        process.stderr.write(
          `\n  ✗ vendored CRD schemas differ from ${source.origin}:\n` +
            `${drifted.map((d) => `      schemas/crd/${d}`).join("\n")}\n`,
        );
      }
      process.stderr.write(
        "\n    Fixes belong upstream in nanohype/eks-agent-platform. To adopt a newer operator\n" +
          "    API here, run `npm run schemas:sync -- --ref=latest` and review the schema diff.\n" +
          "    Never hand-edit a file under schemas/crd/.\n\n",
      );
      process.exit(1);
    }
    out(
      `✓ ${manifest.files.length} vendored CRD schemas match their recorded digests and are ` +
        `byte-identical to ${source.origin}`,
    );
    return;
  }

  const pinned = { ...manifest, upstream: { ...manifest.upstream, ref: source.head }, files };
  await writeFile(SOURCE_PATH, `${JSON.stringify(pinned, null, 2)}\n`);
  out(`✓ vendored from ${source.origin}; pin and digests rewritten`);
}

main().catch((err) => {
  process.stderr.write(`\n  ✗ sync-crd-schemas failed: ${err.stack ?? err.message}\n\n`);
  process.exit(1);
});
